"""Exercise the production TF generator and emit its MSL for GPU readback tests."""
import ast
import contextlib
import io
import json
from pathlib import Path
import re
import sys
import struct
import unittest


def generator(name="vs_tf"):
    path = Path(__file__).resolve().parents[1] / "tools" / "dmsh_build.py"
    tree = ast.parse(path.read_text())
    function = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == name)
    namespace = {"re": re, "sys": sys, "struct": struct, "TF_SLOT": 8}
    exec(compile(ast.Module(body=[function], type_ignores=[]), str(path), "exec"), namespace)
    return namespace[name]


def source(base=False, vertex=True, interleaved=False):
    params = ["uint vid [[vertex_id]]"] if vertex else []
    if base:
        params.append("uint base [[base_vertex]]")
    value = "float(vid)" if vertex else "7.0"
    second = "float4 m_1 [[user(locn1)]];" if interleaved else ""
    values = f"out.m_0 = float4({value}, {value}+1, {value}+2, 0); out.m_1 = out.m_0 + 100;" if interleaved else f"out.m_0 = float4({value});"
    return (
        "#include <metal_stdlib>\nusing namespace metal;\n"
        f"struct main0_out {{ float4 gl_Position [[position]]; float4 m_0 [[user(locn0)]]; {second} }};\n"
        f"vertex main0_out main0({', '.join(params)}) {{\n"
        f"main0_out out = {{}}; out.gl_Position = float4(0, 0, 0, 1); {values}\n"
        "return out;\n}\n"
    )


class TransformFeedbackTests(unittest.TestCase):
    def test_draw_origin_is_subtracted(self):
        result = generator()(source(), [[[[0, 1]], 4]])
        self.assertIn("(vid - dm_tf_base) * 1", result)
        self.assertEqual(result.count("[[base_vertex]]"), 1)

    def test_existing_origin_is_reused(self):
        result = generator()(source(base=True), [[[[0, 1]], 4]])
        self.assertIn("(vid - base) * 1", result)
        self.assertEqual(result.count("[[base_vertex]]"), 1)

    def test_missing_vertex_id_is_added(self):
        result = generator()(source(vertex=False), [[[[0, 1]], 4]])
        self.assertIn("(dm_vid - dm_tf_base) * 1", result)
        self.assertEqual(result.count("[[vertex_id]]"), 1)

    def test_interleaved_outputs(self):
        for components in ([3, 3], [3, 3, 3, 4], [4] * 9):
            control = bytearray(0x708)
            struct.pack_into("<H", control, 0x6dc, sum(components) * 4)
            control[0x6e8] = len(components)
            control[0xdc:0xdc + len(components)] = bytes(0x20 + i for i in range(len(components)))
            control[0x4dc:0x4dc + len(components)] = bytes(components)
            layout = generator("tf_layout")("fixture", control)
            self.assertEqual(layout[0], [[[i, n] for i, n in enumerate(components)], sum(components) * 4])
            result = generator()(source(), layout)
            self.assertEqual(result.count(" = as_type<uint>(") + result.count(" = 0u;"), sum(components))
            self.assertIn(f"* {sum(components)} + {sum(components) - 1}]", result)

    def test_inconsistent_stride_is_rejected(self):
        control = bytearray(0x708)
        struct.pack_into("<H", control, 0x6dc, 12)
        control[0x6e8] = 1; control[0xdc] = 0x20; control[0x4dc] = 4
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertIsNone(generator("tf_layout")("fixture", control))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--header":
        path = Path(sys.argv[2])
        path.parent.mkdir(parents=True, exist_ok=True)
        variants = [source(), source(base=True), source(vertex=False), source(interleaved=True)]
        contents = "// Generated by test_tf.py from the production TF generator.\n"
        for index, original in enumerate(variants):
            layout = [[[[0, 3], [1, 3]], 24]] if index == 3 else [[[[0, 1]], 4]]
            msl = original + generator()(original, layout)
            contents += f"static const char tf_source_{index}[] = {json.dumps(msl)};\n"
        path.write_text(contents)
    else:
        unittest.main()
