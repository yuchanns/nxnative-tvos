"""Build an independent 17-binding fixture for the production compact encoder."""
import argparse
import json
from pathlib import Path
import sys
import unittest
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from dmsh_legacy import LoweringError, compact_samplers

BINDINGS = [
    {"msl_name": "texture", "msl_type": "texture2d<float>", "arg_id": 0, "kind": "tex", "reg": 0},
    {"msl_name": "output", "msl_type": "device uint*", "arg_id": 1, "kind": "sbuf", "reg": 0, "rw": True},
] + [{"msl_name": f"s{i}", "msl_type": "sampler", "arg_id": i + 2, "kind": "samp", "reg": i} for i in range(17)]
SOURCE = ("#include <metal_stdlib>\nusing namespace metal;\nstruct spvDescriptorSetBuffer0 {\n"
          "texture2d<float> texture [[id(0)]]; device uint* output [[id(1)]];\n" +
          "\n".join(f"sampler s{i} [[id({i + 2})]];" for i in range(17)) +
          "\n};\nkernel void main0(constant spvDescriptorSetBuffer0 &spvDescriptorSet0 [[buffer(0)]]) {\n" +
          "\n".join(f"spvDescriptorSet0.output[{i}] = uint(round(spvDescriptorSet0.texture.sample(spvDescriptorSet0.s{i}, float2(1.25, 0.5)).r));" for i in range(17)) + "\n}\n")

class LegacySamplerTests(unittest.TestCase):
    def test_mapping(self):
        source, metadata = compact_samplers(SOURCE, BINDINGS)
        self.assertEqual(metadata["arg_ids"], list(range(2, 19)))
        self.assertEqual(metadata["table_arg"], 19)
        self.assertEqual(metadata["map_arg"], 35)
        self.assertIn("dm_sampler_map[16]", source)
        self.assertNotIn("sampler s0", source)

    def test_unknown_use(self):
        with self.assertRaises(LoweringError):
            compact_samplers(SOURCE.replace("spvDescriptorSet0.s0,", "unknown.s0,"), BINDINGS)

    def test_interleaved_resources(self):
        source = SOURCE.replace("sampler s1 [[id(3)]];", "texture2d<float> second [[id(3)]];\nsampler s1 [[id(19)]];")
        bindings = [dict(binding, arg_id=19) if binding["msl_name"] == "s1" else binding for binding in BINDINGS]
        source, _ = compact_samplers(source, bindings)
        self.assertLess(source.index("second [[id(3)]]"), source.index("dm_sampler_table [[id(20)]]"))

    def test_small_set(self):
        self.assertEqual(compact_samplers(SOURCE, BINDINGS[:18]), (SOURCE, None))

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", type=Path)
    args, rest = parser.parse_known_args()
    if args.header:
        source, metadata = compact_samplers(SOURCE, BINDINGS)
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text("// Generated by test_legacy_samplers.py.\nstatic const char *legacy_sampler_source = " + json.dumps(source) + ";\n")
    else:
        unittest.main(argv=[sys.argv[0], *rest])
