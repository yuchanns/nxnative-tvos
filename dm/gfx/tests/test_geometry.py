"""Canonical capture uses original vertex IDs and preserves register bit patterns."""
import json
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
import dmsh_geometry
import c1_guard


def fixture():
    return '''#include <metal_stdlib>
using namespace metal;
struct main0_out {
    float4 position [[position]];
    uint4 data [[user(locn0)]];
    float clips [[clip_distance]] [2];
};
vertex main0_out main0(uint vid [[vertex_id]], uint instance [[instance_id]]) {
    main0_out out = {};
    out.position = float4(float(vid), float(instance), -0.5f, 2.0f);
    out.data = uint4(vid, instance, 0x7fc12345u, 0xffffffffu);
    out.clips[0] = -3.0f; out.clips[1] = 4.0f;
    return out;
}
'''


class GeometryTests(unittest.TestCase):
    def test_discard_preserves_writes_and_early_returns(self):
        source = fixture().replace('    return out;', '    storage[vid] = instance;\n    if (vid) return out;\n    return out;')
        discard = dmsh_geometry.discard(source)
        self.assertIn('vertex void main0_discard(uint vid [[vertex_id]], uint instance [[instance_id]])', discard)
        self.assertIn('storage[vid] = instance;', discard)
        self.assertIn('if (vid) return;', discard)
        self.assertNotIn('return out;', discard)
        self.assertNotIn('dm_capture_', discard)

    def test_parameterless_vertex_entry(self):
        source = fixture().replace('uint vid [[vertex_id]], uint instance [[instance_id]]', '')
        source = source.replace('vid', '7u').replace('instance', '11u')
        capture = dmsh_geometry.capture(source)
        self.assertIn('main0_gc(uint dm_capture_vertex_id [[vertex_id]]', capture)
        self.assertNotIn('main0_gc(,', capture)

    def test_prefixed_geometry_constants_are_checked(self):
        source = '(*vp_c1)._m0[0] + (*dm_g6_gp_c1)._m0[dynamic_index]'
        self.assertEqual(['0', 'dynamic_index'], c1_guard.ACCESS.findall(source))
        self.assertFalse(c1_guard.proven('dynamic_index', {}, 512))

    def test_original_position_and_bits(self):
        capture = dmsh_geometry.capture(fixture())
        self.assertIn('as_type<uint>(out.position.z)', capture)
        self.assertIn('as_type<uint>(out.data.z)', capture)
        self.assertIn('dm_capture_at[5] = as_type<uint>(out.clips[0])', capture)
        self.assertNotIn('0.5', capture[:capture.index('{')])

    def test_sparse_index_origin(self):
        capture = dmsh_geometry.capture(fixture())
        self.assertIn('vid - dm_capture_info[2]', capture)
        self.assertIn('instance - dm_capture_info[3]', capture)
        self.assertIn('dm_capture_ids[dm_mid] < dm_capture_id', capture)
        self.assertIn('dm_capture_info[6]', capture)

    def test_unknown_output_rejected(self):
        with self.assertRaises(ValueError):
            dmsh_geometry.capture(fixture().replace('user(locn0)', 'viewport_array_index'))


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--header':
        path = Path(sys.argv[2]); path.parent.mkdir(parents=True, exist_ok=True)
        source = fixture(); source += dmsh_geometry.capture(source)
        path.write_text('// Generated by test_geometry.py.\nstatic const char geometry_capture_source[] = ' + json.dumps(source) + ';\n')
    else:
        unittest.main()
